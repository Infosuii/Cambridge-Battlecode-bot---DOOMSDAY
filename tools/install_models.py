"""The single switch for installing models (agent B; CONTRACTS section 5).

    python tools/install_models.py --profile teacher_exact          # checked-in state: every head off
    python tools/install_models.py --profile release                 # validated + selected models only
    python tools/install_models.py --profile dev_untrained --src artifacts/tmp/x/src   # scratch tree

Regenerates, from models/registry.json + configs/profiles/<profile>.json + models/budget.json + the schemas found
in the target tree:
  <src>/nn_config.h        (tools/gen_config.py render)
  <src>/nn_registry.h      (budget constants, head -> model table, action schema hashes)
  <src>/nn_weights_<m>.h   (re-rendered from models/<m>/weights.f32 after checksum verification; stale ones removed)
Gameplay code is never edited. Prints the per-head plan (mode, model, reason) and writes a JSON receipt.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'python'))
sys.path.insert(0, str(ROOT / 'tools'))

from nfs import export, registry  # noqa: E402
from nfs.models.config import HEAD_NAMES, canonical_json  # noqa: E402
from nfs.models.rt import fnv1a32  # noqa: E402
import gen_config  # noqa: E402


def budget_values(budget: dict, plan: dict) -> dict:
    pol = budget['policy']
    n = len(HEAD_NAMES)
    fixed, per = [0] * n, [0] * n
    enc = 0
    for i, h in enumerate(HEAD_NAMES):
        mname = plan['heads'][h]['model']
        if not mname:
            continue
        costs = registry.model_costs(plan['manifests'][mname]['config'], budget)
        fixed[i] = costs['heads'][h]['fixed'] + pol['decide_fixed']
        per[i] = costs['heads'][h]['per_cand']
        if plan['ctx_model'] == mname:
            enc = costs['encoder']
    return dict(turn_allowance=pol['turn_allowance'], tail_reserve=pol['tail_reserve'],
                teacher_reserve=[int(pol['teacher_reserve'].get(h, pol['teacher_reserve']['default'])) for h in HEAD_NAMES],
                capture_worst=pol['capture_worst'], obs_encode_worst=pol['obs_encode_worst'], encoder_worst=enc,
                head_fixed=fixed, head_per_cand=per, log_fixed=pol['log_fixed'], log_per_byte=pol['log_per_byte'],
                verify_per_float=pol['verify_per_float'], verify_chunk=pol['verify_chunk'],
                max_records_per_turn=pol['max_records_per_turn'])


def render_registry(profile: dict, plan: dict, bv: dict, head_hashes: dict) -> str:
    models = plan['models']
    idx = {m: i for i, m in enumerate(models)}
    arr = lambda xs: '{' + ', '.join(f'{int(x)}u' if not isinstance(x, str) else x for x in xs) + '}'  # noqa: E731
    head_model = [idx.get(plan['heads'][h]['model'], -1) if plan['heads'][h]['model'] else -1 for h in HEAD_NAMES]
    ahash = [f'0x{(head_hashes.get(h) or 0):08x}u' for h in HEAD_NAMES]
    phash = fnv1a32(canonical_json(profile))
    out = [
        f'// GENERATED by tools/install_models.py --profile {profile["name"]} - do not edit.',
        '// Base section: budget policy + measured costs (models/budget.json) and the head -> model table.',
        '// Model section (only with NN_REGISTRY_WANT_MODELS, i.e. in nn_head.cpp): the installed weight headers.',
        '#ifndef NN_REGISTRY_BASE_H',
        '#define NN_REGISTRY_BASE_H',
        '#include <cstdint>',
        '',
        'namespace nnreg {',
        f'inline constexpr const char* kProfile = "{profile["name"]}";',
        f'inline constexpr std::uint32_t kProfileHash = 0x{phash:08x}u;',
        f'inline constexpr std::uint64_t kTurnAllowance = {bv["turn_allowance"]}u;',
        f'inline constexpr std::uint64_t kTailReserve = {bv["tail_reserve"]}u;',
        f'inline constexpr std::uint64_t kTeacherReserve[{len(HEAD_NAMES)}] = {arr(bv["teacher_reserve"])};',
        f'inline constexpr std::uint64_t kCaptureWorst = {bv["capture_worst"]}u;   // nnobs::capture (agent C)',
        f'inline constexpr std::uint64_t kObsEncodeWorst = {bv["obs_encode_worst"]}u; // nnobs::encode (agent C)',
        f'inline constexpr std::uint64_t kEncoderWorst = {bv["encoder_worst"]}u;  // shared encoder forward',
        f'inline constexpr std::uint64_t kHeadFixed[{len(HEAD_NAMES)}] = {arr(bv["head_fixed"])};',
        f'inline constexpr std::uint64_t kHeadPerCand[{len(HEAD_NAMES)}] = {arr(bv["head_per_cand"])};',
        f'inline constexpr std::uint64_t kLogFixed = {bv["log_fixed"]}u;',
        f'inline constexpr std::uint64_t kLogPerByte = {bv["log_per_byte"]}u;',
        f'inline constexpr std::uint64_t kVerifyPerFloat = {bv["verify_per_float"]}u;',
        f'inline constexpr std::uint32_t kVerifyChunk = {bv["verify_chunk"]}u;',
        f'inline constexpr std::uint32_t kMaxRecordsPerTurn = {bv["max_records_per_turn"]}u;',
        f'inline constexpr std::uint32_t kHeadActionHash[{len(HEAD_NAMES)}] = {{{", ".join(ahash)}}};',
        f'inline constexpr int kNumModels = {len(models)};',
        f'inline constexpr int kHeadModel[{len(HEAD_NAMES)}] = {{{", ".join(str(x) for x in head_model)}}};',
        f'inline constexpr int kCtxModel = {idx.get(plan["ctx_model"], -1) if plan["ctx_model"] else -1};',
        '} // namespace nnreg',
        '#endif // NN_REGISTRY_BASE_H',
        '',
        '#if defined(NN_REGISTRY_WANT_MODELS) && !defined(NN_REGISTRY_MODELS_H)',
        '#define NN_REGISTRY_MODELS_H',
        '#include "nn_model.h"',
        *[f'#include "nn_weights_{m}.h"' for m in models],
        'namespace nnreg {',
        f'inline constexpr const nnm::ModelDesc* kModels[{max(1, len(models))}] = '
        f'{{{", ".join(f"&nnw_{m}::kDesc" for m in models) or "nullptr"}}};',
        '} // namespace nnreg',
        '#endif // NN_REGISTRY_MODELS_H',
        '',
    ]
    return '\n'.join(out)


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def install(profile_name: str, src: Path, root: Path = ROOT, budget_path: Path | None = None,
            receipt: Path | None = None, quiet: bool = False, model: str | None = None,
            registry_path: Path | None = None) -> dict:
    src = Path(src)
    prof = registry.load_profile(profile_name, root)
    if model:
        if prof['model'] == 'release_selection':
            raise SystemExit('--model cannot override the release selection (edit models/registry.json)')
        prof = dict(prof, model=model, name=prof['name'])
    reg = registry.load_json(registry_path) if registry_path else registry.load_registry(root)
    plan = registry.resolve_profile(prof, reg, root, src)
    budget = json.loads(Path(budget_path or root / 'models/budget.json').read_text(encoding='utf-8'))
    head_hashes = {}
    for m in plan['models']:
        head_hashes.update({k: v for k, v in registry.current_head_hashes(
            root, manifest_cfg=plan['manifests'][m]['config']).items() if v is not None})
    bv = budget_values(budget, plan)
    written = []
    keep = {f'nn_weights_{m}.h' for m in plan['models']}
    for old in src.glob('nn_weights_*.h'):
        if old.name not in keep:
            old.unlink()
    for m in plan['models']:
        man, blob = export.load_blob(root / reg['models'][m]['path'])
        segs = export.segment_checksums(man['config'], blob)
        if segs != man['segment_checksums']:
            raise SystemExit(f'{m}: segment checksums differ from manifest')
        text = export.render_header(m, man['config'], blob, man['status'], segs, man['checksum'],
                                    man.get('note', ''))
        p = src / f'nn_weights_{m}.h'
        p.write_text(text, encoding='utf-8', newline='\n')
        written.append(p)
    p = src / 'nn_registry.h'
    p.write_text(render_registry(prof, plan, bv, head_hashes), encoding='utf-8', newline='\n')
    written.append(p)
    p = src / 'nn_config.h'
    p.write_text(gen_config.render(prof, plan), encoding='utf-8', newline='\n')
    written.append(p)
    summary = dict(profile=prof['name'], src=str(src), any_head=plan['any_head'], models=plan['models'],
                   model_paths={m: reg['models'][m]['path'] for m in plan['models']},
                   ctx_model=plan['ctx_model'], notes=plan['notes'],
                   heads={h: {k: plan['heads'][h][k] for k in ('mode', 'model', 'requested', 'reason')}
                          for h in HEAD_NAMES},
                   budget=bv, files={str(f.name): sha(f) for f in written})
    if receipt:
        Path(receipt).parent.mkdir(parents=True, exist_ok=True)
        Path(receipt).write_text(json.dumps(summary, indent=2) + '\n', encoding='utf-8')
    if not quiet:
        print(f'profile {prof["name"]} -> {src}')
        for h in HEAD_NAMES:
            r = plan['heads'][h]
            print(f'  {h:11s} {r["mode"]:7s} {r["model"] or "-":18s} {r["reason"] or ""}')
        for n in plan['notes']:
            print('  note:', n)
    return summary


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--profile', required=True)
    ap.add_argument('--src', default=str(ROOT / 'bot/src'))
    ap.add_argument('--budget', default=None)
    ap.add_argument('--receipt', default=None, help='JSON receipt path (default models/installed.json for bot/src)')
    ap.add_argument('--model', default=None, help='override the profile model (not allowed for release)')
    a = ap.parse_args(argv)
    src = Path(a.src).resolve()
    receipt = a.receipt or (ROOT / 'models/installed.json' if src == (ROOT / 'bot/src').resolve() else None)
    install(a.profile, src, ROOT, Path(a.budget) if a.budget else None, Path(receipt) if receipt else None,
            model=a.model)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
