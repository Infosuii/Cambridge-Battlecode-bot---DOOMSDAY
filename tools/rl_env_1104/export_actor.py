"""actor.json (format jd-cl1-pointer-f32-v1, JOHNDOE tools/rl_learner_1104/export_cl1.py) -> C++ weights header.

Every value is written as an exact float32 hex literal (round-trips bit for bit). The header records the SHA-256 of the
source actor.json so a bot build names the exact model it runs. Standard library only.

usage: python tools/rl_env_1104/export_actor.py ACTOR.json OUT.h [--parity PARITY.json --parity-out PARITY.h]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct

FORMAT = "jd-cl1-pointer-f32-v1"
PREPROCESS = "jd-cl1-af91-v1"
# name in actor.json -> (C identifier, expected shape)
TENSORS = {
    "encoders.ally.weight": ("enc_ally_w", [8, 20]), "encoders.ally.bias": ("enc_ally_b", [8]),
    "encoders.altar.weight": ("enc_altar_w", [8, 4]), "encoders.altar.bias": ("enc_altar_b", [8]),
    "encoders.camp.weight": ("enc_camp_w", [8, 19]), "encoders.camp.bias": ("enc_camp_b", [8]),
    "encoders.enemy.weight": ("enc_enemy_w", [8, 23]), "encoders.enemy.bias": ("enc_enemy_b", [8]),
    "context.weight": ("ctx_w", [32, 122]), "context.bias": ("ctx_b", [32]),
    "memory.weight_ih": ("gru_wih", [48, 32]), "memory.weight_hh": ("gru_whh", [48, 16]),
    "memory.bias_ih": ("gru_bih", [48]), "memory.bias_hh": ("gru_bhh", [48]),
    "pointer.weight": ("ptr_w", [16, 24]), "pointer.bias": ("ptr_b", [16]),
    "score.weight": ("score_w", [1, 16]), "score.bias": ("score_b", [1]),
    "none.weight": ("none_w", [1, 16]), "none.bias": ("none_b", [1]),
}


def f32(v: float) -> float:
    return struct.unpack("<f", struct.pack("<f", v))[0]


def lit(v: float) -> str:
    """Exact C++ float literal for a float32 value."""
    if v != v or v in (float("inf"), float("-inf")):
        raise ValueError("non-finite weight")
    return float.hex(f32(v)).replace("0x1.0000000000000p", "0x1p") + "f" if v != 0 else "0.0f"


def array(name: str, values: list) -> str:
    body = ",".join(lit(v) for v in values)
    return f"inline constexpr float {name}[{len(values)}] = {{{body}}};\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("actor")
    ap.add_argument("out")
    ap.add_argument("--parity")
    ap.add_argument("--parity-out")
    a = ap.parse_args()
    raw = open(a.actor, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    actor = json.loads(raw)
    if actor.get("format") != FORMAT or actor.get("preprocess") != PREPROCESS:
        raise SystemExit(f"unsupported actor format {actor.get('format')}/{actor.get('preprocess')}")
    if actor.get("pool_order") != ["ally", "altar", "camp", "enemy"] or actor.get("hidden") != 16:
        raise SystemExit("unexpected pool order or hidden size")
    out = [f"// Generated by tools/rl_env_1104/export_actor.py from actor.json sha256 {sha}. Do not edit.\n",
           f"// format {FORMAT}, preprocess {PREPROCESS}, encoder source {actor.get('encoder_source')}.\n",
           "#pragma once\nnamespace clrl_w {\n", f'inline constexpr char kActorSha256[] = "{sha}";\n']
    for key, (name, shape) in TENSORS.items():
        t = actor["tensors"][key]
        if t["shape"] != shape:
            raise SystemExit(f"{key}: shape {t['shape']} != {shape}")
        out.append(array(name, t["values"]))
    out.append("}  // namespace clrl_w\n")
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    if a.parity:
        p = json.load(open(a.parity, encoding="utf-8"))
        n = len(p["raw"])
        po = [f"// Generated parity fixtures from {a.parity} (actor sha256 {p.get('actor_sha256')}). Do not edit.\n",
              "#pragma once\n#include <cstdint>\nnamespace clrl_fx {\n", f"inline constexpr int kN = {n};\n",
              "inline constexpr std::int16_t raw[%d][448] = {%s};\n" % (n, ",".join("{" + ",".join(str(int(v)) for v in r) + "}" for r in p["raw"])),
              array("hidden_in", [v for r in p["hidden_in"] for v in r]),
              "inline constexpr bool reset[%d] = {%s};\n" % (n, ",".join("true" if v else "false" for v in p["reset"]))]
        po.append("}  // namespace clrl_fx\n")
        with open(a.parity_out, "w", encoding="utf-8", newline="\n") as f:
            f.write("".join(po))
    print(f"wrote {a.out} (actor sha256 {sha[:16]})")


if __name__ == "__main__":
    main()
