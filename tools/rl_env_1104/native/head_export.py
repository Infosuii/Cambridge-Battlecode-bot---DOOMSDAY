"""Export the native target head (JOHNDOE's TargetHead, 11826 float32) to bots/claude-native-1104/src/clna_head_w.h.

Packing = JOHNDOE's export_probe.py / optimized_head.h: for context, query, key, features, far, gate in that order, the
weight transposed to input-major, then the bias. Without --checkpoint the head is a fresh deterministic init
(torch.manual_seed(--seed), JOHNDOE's zero query / far / gate weight and gate bias logit(--eps)): its policy equals the
CLNA_EPS mixture exactly (zero residual, alpha = eps).

Head ABI (clna-head-abi-v1, CLNA_HEAD in nnrec.cpp), inputs as float32 = exact scalings of logged integers:
  context[160] = nn_lv.x (frozen Q16 trunk input, Q10) * 2^-10, at the moment nn_pub was built (snapshot)
  camps[n][16] = nn_lv.ec[slot] (frozen camp embedding, Q10) * 2^-10 for the n valid scored slots, nn_pub order
  features[n][4] (camp block fields of the same slot, clipped then scaled by powers of two):
      0 walking distance  f[16]: unknown (-1) -> 256; clip [0, 256] / 32
      1 allies claiming   f[14]: clip [0, 8] / 4
      2 allies closer     f[20]: clip [0, 8] / 4
      3 our committed target f[21]: 0 / 1
  native[n + 1] = nn_pub.es (the frozen runtime's slot logits) and nn_pub.far (the far slot -> v92's group)

usage: python tools/rl_env_1104/native/head_export.py [--checkpoint head.pt] [--seed 1104] [--eps 0.02] [--out PATH]
"""
import argparse
import hashlib
import json
import math
import os
import sys

import torch

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, HERE)
from target_head import TargetHead  # noqa: E402

HEAD_ABI = ("clna-head-abi-v1|ctx=nn_lv.x*2^-10[160]|camp=nn_lv.ec*2^-10[16]|"
            "feat=wd(-1->256,clip0..256)/32,claim(clip0..8)/4,closer(clip0..8)/4,committed|native=nn_pub.es+far|"
            "jd_head e6807c95|n<=10")
HEAD_ABI_HASH = hashlib.sha256(HEAD_ABI.encode()).hexdigest()
LAYERS = ("context", "query", "key", "features", "far", "gate")


def fresh(seed: int, eps: float) -> TargetHead:
    torch.manual_seed(seed)
    m = TargetHead()
    with torch.no_grad():
        m.gate.bias.fill_(math.log(eps / (1 - eps)))
    return m


def pack(m: TargetHead) -> list:
    out = []
    for name in LAYERS:
        layer = getattr(m, name)
        out += layer.weight.detach().to(torch.float32).T.contiguous().flatten().tolist()
        out += layer.bias.detach().to(torch.float32).tolist()
    assert len(out) == 11826
    return out


def unpack(w: list) -> TargetHead:
    """Inverse of pack(): the TargetHead whose export is exactly w (float32 values)."""
    m, i = TargetHead(), 0
    with torch.no_grad():
        for name in LAYERS:
            layer = getattr(m, name)
            o, n = layer.weight.shape
            layer.weight.copy_(torch.tensor(w[i:i + n * o], dtype=torch.float32).view(n, o).T)
            i += n * o
            layer.bias.copy_(torch.tensor(w[i:i + o], dtype=torch.float32))
            i += o
    assert i == len(w) == 11826
    return m


def load_header(path: str) -> tuple:
    """(TargetHead, version) from a generated clna_head_w.h: the deployed weights, not a re-derivation."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    ver = text.split('kVersion[] = "', 1)[1].split('"', 1)[0]
    abi = text.split('kAbiHash[] = "', 1)[1].split('"', 1)[0]
    if abi != HEAD_ABI_HASH:
        raise ValueError(f"{path}: head ABI {abi[:12]} != {HEAD_ABI_HASH[:12]}")
    body = text.split("kW[11826] = {", 1)[1].split("}", 1)[0]
    return unpack([float.fromhex(v.strip().rstrip("f")) for v in body.split(",")]), ver


def header(m: TargetHead, tag: str) -> tuple:
    w = pack(m)
    ver = f"clna-head-v1-{tag}-" + hashlib.sha256(json.dumps(w).encode()).hexdigest()[:12]
    body = ",".join(float.hex(float(v)) + "f" for v in w)
    text = ("// Generated by tools/rl_env_1104/native/head_export.py. Do not edit.\n"
            f"// {HEAD_ABI}\n#pragma once\nnamespace clna_head {{\n"
            f'inline constexpr char kVersion[] = "{ver}";\n'
            f'inline constexpr char kAbiHash[] = "{HEAD_ABI_HASH}";\n'
            f"alignas(16) inline constexpr float kW[11826] = {{{body}}};\n}}  // namespace clna_head\n")
    return text, ver


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--checkpoint")
    ap.add_argument("--seed", type=int, default=1104)
    ap.add_argument("--eps", type=float, default=0.02)
    ap.add_argument("--out", default=os.path.join(ROOT, "bots", "claude-native-1104", "src", "clna_head_w.h"))
    a = ap.parse_args()
    if a.checkpoint:
        ck = torch.load(a.checkpoint, weights_only=True)
        if ck["head_abi_hash"] != HEAD_ABI_HASH:
            raise SystemExit("checkpoint head ABI differs")
        m = TargetHead()
        m.load_state_dict(ck["head"])
        tag = f"u{ck['updates']}"
    else:
        m, tag = fresh(a.seed, a.eps), f"init{a.seed}"
    text, ver = header(m, tag)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(ver, a.out)


if __name__ == "__main__":
    main()
