"""Generate the Z13 scripted style opponents from DZ's own source (evaluation only, never candidates).

Usage: python tools/dz_styles.py   -> bots/dzs-rusher, bots/dzs-turtle, bots/dzs-farmer (git-ignored, regenerated)

Each is a copy of bots/dz/src with `#define DZ_STYLE n` (1 rusher, 2 turtle, 3 cluster farmer). They contain no
previous-bot code. Use them with `tools/dz.py smoke --opponent dzs-rusher` etc.
"""
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STYLES = {'dzs-rusher': 1, 'dzs-turtle': 2, 'dzs-farmer': 3}

for name, value in STYLES.items():
    dest = ROOT / 'bots' / name
    shutil.rmtree(dest, ignore_errors=True)
    shutil.copytree(ROOT / 'bots/dz/src', dest / 'src')
    config = dest / 'src/config.h'
    text, n = re.subn(r'^#define DZ_STYLE 0\b.*$', f'#define DZ_STYLE {value} // Generated by tools/dz_styles.py.',
                      config.read_text(encoding='utf-8'), count=1, flags=re.M)
    if n != 1:
        raise ValueError('DZ_STYLE default not found in bots/dz/src/config.h')
    config.write_text(text, encoding='utf-8', newline='\n')
    (dest / 'README.md').write_text(f'Generated by tools/dz_styles.py (DZ_STYLE {value}); evaluation opponent only.\n', encoding='utf-8')
    print(dest.relative_to(ROOT))
