"""Write bots/x3/src/x1_categories.h from research/x3/atlas/categories_rules.json (tools/mapatlas/categorise.py
--source bot): the category tree as C++ over the bot's own atlas features (x1_atlas.h), so the bot categorises any
map (seen or not) exactly as the offline analysis did.
  python tools/mapatlas/gen_categories.py
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]

# Same expressions as categorise.BOT_FEATS, in C++ over x1_atlas::Features f.
EXPR = {
    'log_area': 'std::log(static_cast<float>(f.w) * static_cast<float>(f.h))',
    'team': 'static_cast<float>(f.team)',
    'contested': 'f.contested',
    'top3': 'f.top3',
    'log_density': 'std::log(1.0f + static_cast<float>(f.gems) * 100.0f / (static_cast<float>(f.w) * static_cast<float>(f.h)))',
    'groups_per_champ': 'static_cast<float>(f.groups) / (2.0f * static_cast<float>(std::max(1, f.team)))',
    'harmless': 'f.harmless',
    'strong': 'f.strong',
    'blocked': 'f.blocked',
    'unreachable': 'f.unreachable',
    'near15': 'f.near15',
    'near30': 'f.near30',
    'log_mean_dist': 'std::log(1.0f + f.mean_dist)',
    'log_hp_per_gem': 'std::log(1.0f + f.hp_per_gem)',
}


def main():
    R = json.loads((ROOT / 'research/x3/atlas/categories_rules.json').read_text())
    tree, leaves = R['tree'], R['leaves']  # leaves: {name: [conditions]}
    path_to_name = {tuple(v): k for k, v in leaves.items()}
    names = sorted(leaves, key=lambda n: int(n[1:]))

    def emit(node, path, ind):
        if 'leaf' in node:
            return [f'{ind}return {int(path_to_name[tuple(path)][1:]) - 1}; // {path_to_name[tuple(path)]}']
        f, t = node['feat'], node['thr']
        le = emit(node['le'], path + [f'{f} <= {t}'], ind + '    ')
        gt = emit(node['gt'], path + [f'{f} > {t}'], ind + '    ')
        return [f'{ind}if ({EXPR[f]} <= {t}f) {{'] + le + [f'{ind}}}'] + gt
    body = emit(tree, [], '    ')
    lines = ['// Map categories (generated by tools/mapatlas/gen_categories.py from research/x3/atlas/categories_rules.json;',
             '// see research/x3/atlas/CATEGORIES.md). Index = category number - 1.', '#pragma once', '#include "x1_atlas.h"',
             '#include <cmath>', '', 'namespace x1_categories {', '', f'inline constexpr int kNumCats = {len(names)};', '',
             'inline int classify(const x1_atlas::Features& f) {'] + body + ['}', '', '} // namespace x1_categories', '']
    (ROOT / 'bots/x3/src/x1_categories.h').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('wrote bots/x3/src/x1_categories.h with', len(names), 'categories')


if __name__ == '__main__':
    main()
