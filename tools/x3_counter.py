"""Counter table for x3 (X1_COUNTER): per map and side, the variant of our play that beat the opponent there.

Games are deterministic per (map, side, both bots), so a variant that won a map and side against an opponent wins it
again with the same builds. `vars` writes the variant list into bots/x3/src/x1_counter.h; each search build forces one
variant on every map (X1_COUNTER_FORCE=k) and plays the pool; `table` reads those runs and writes the rows: for each
(map, side) where variant 0 (v92's own play) lost, the first variant that won.

  python tools/x3_counter.py vars
  python tools/x3_counter.py table --runs ctr-v92-k{K} --vars 1-29 [--opp v92]
  python tools/x3_counter.py robust --runs ctr3-{OPP}-k{K} --opps x3mf,x3inv,v86h,x1bru --vars 0-29 --fp research/x3/counter_fp.json
    robust: per (map, side), the variant with the most wins summed over several opponents (ties keep variant 0),
    switched only when it beats variant 0 by --margin wins; prints in-sample wins per opponent and a
    leave-one-opponent-out estimate (cells chosen on the other opponents, scored on the left-out one).
"""
import argparse, json, random, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
HDR = ROOT / 'bots/x3/src/x1_counter.h'
DIMS = 24
MAX_ROWS = 176



def full_groups(m):
    """Group count and gem total of the whole map, as the bot sees them at runtime (w.groups): the map file holds the
    authored half, so each group is mirrored; a group that maps onto itself (it straddles the mirror line) counts once."""
    w, h, sym = m['w'], m['h'], m['symmetry']
    def mirror(x, y):
        if sym == 'horizontal': return w - 1 - x, y
        if sym == 'vertical': return x, h - 1 - y
        return w - 1 - x, h - 1 - y
    n = gems = 0
    for g in m['groups']:
        cells = sorted((c['x'], c['y']) for c in g['camps'])
        n += 1; gems += g['gems']
        if cells and sorted(mirror(x, y) for x, y in cells) != cells: n += 1; gems += g['gems']
    return n, gems

def variants():
    v = [(0, -1, [0.0] * DIMS)]                                   # 0: own play
    v += [(p, 0, [0.0] * DIMS) for p in range(1, 9)]               # 1-8: plans 1-8 all game
    v += [(4, 150, [0.0] * DIMS), (7, 250, [0.0] * DIMS), (3, 300, [0.0] * DIMS), (8, 300, [0.0] * DIMS),
          (2, 300, [0.0] * DIMS)]                                  # 9-13: late plans
    rng = random.Random(92)
    v += [(0, -1, [round(rng.gauss(0, 0.6), 3) for _ in range(DIMS)]) for _ in range(16)]  # 14-29: knob vectors
    return v


def write_header(rows):
    vs = variants()
    lines = ['// Counter table for x3 (X1_COUNTER), generated by tools/x3_counter.py: per map fingerprint and absolute team,',
             '// the variant of our play (team plan + knob deltas on ladfit\'s 24 dimensions) that beat the opponent there.',
             '#pragma once', '#include <cstdint>', 'namespace x1_counter {', f'inline constexpr int kDims = {DIMS};',
             'inline constexpr int kIdx[kDims] = {0, 1, 2, 3, 4, 5, 8, 9, 10, 11, 12, 22, 23, 43, 45, 46, 55, 57, 60, 61, 64, 65, 50, 49};',
             'struct Var { int id, round; float d[kDims]; };', 'inline constexpr Var kVars[] = {']
    for i, (p, r, d) in enumerate(vs):
        lines.append(f"    {{{p}, {r}, {{{', '.join(f'{x:.3f}f' for x in d)}}}}}, // {i}")
    # Rows and the forced variant are volatile data and the lookup is branch-free over a fixed-size table, so every
    # counter build (search builds, table build) runs the same instructions and differs only in its data section:
    # the fuel each turn uses, and so the games, do not depend on the table's contents.
    assert len(rows) <= MAX_ROWS
    pad = ['    -1, -1, -1, -1, -1, 0,'] * (MAX_ROWS - len(rows))
    lines += ['};', f'inline constexpr int kNumVars = {len(vs)};', f'inline constexpr int kMaxRows = {MAX_ROWS};',
              '// w, h, groups, gems, team, variant', 'inline volatile int kRows[kMaxRows * 6] = {']
    lines += rows + pad + ['};', 'inline volatile int kForce = X1_COUNTER_FORCE + 1000; // search builds: variant k everywhere (+1000: never zero, so never moved to .bss)',
                           'inline int sel = 0; // chosen variant (set once at the knob set-up)',
                           '} // namespace x1_counter', '']
    HDR.write_text('\n'.join(lines), newline='\n')


def rng_list(s):
    out = []
    for part in s.split(','):
        a, _, b = part.partition('-'); out += range(int(a), int(b or a) + 1)
    return out


def main():
    ap = argparse.ArgumentParser(); sub = ap.add_subparsers(dest='cmd', required=True)
    sub.add_parser('vars')
    t = sub.add_parser('table'); t.add_argument('--runs', required=True, help='run-name pattern with {K}')
    t.add_argument('--vars', required=True); t.add_argument('--base', default='', help='run name of variant 0 (default: pattern with K=0)')
    t.add_argument('--swap', type=int, default=0, help='1 = team 1 is side A')
    t.add_argument('--fp', help='json {map-side: [w, h, groups, gems, team]} printed by the bot (exact keys)')
    t.add_argument('--run-dirs', default='research/dz/runs,artifacts/tmp/dz')
    r = sub.add_parser('robust'); r.add_argument('--runs', required=True, help='run-name pattern with {OPP} and {K}')
    r.add_argument('--opps', required=True); r.add_argument('--vars', required=True)
    r.add_argument('--margin', type=int, default=1, help='wins over variant 0 (summed over opponents) needed to switch')
    r.add_argument('--fp', required=True); r.add_argument('--write', type=int, default=1)
    r.add_argument('--run-dirs', default='research/dz/runs,artifacts/tmp/dz,../x1-comms/g3/results/L007,../x1-comms/g5060/results/ctr3,../x1-comms/g5070/results/ctr3')
    a = ap.parse_args()
    if a.cmd == 'robust':
        robust(a); return
    if a.cmd == 'vars':
        write_header([]); print(len(variants()), 'variants written'); return
    sys.path.insert(0, str(ROOT / 'tools/mapgen')); import mapio
    def load(name):
        for d in a.run_dirs.split(','):
            p = ROOT / d / name / 'results.json'
            if p.exists():
                return {(g['map'], g['side']): g['outcome'] == ('teamA' if g['side'] == 'A' else 'teamB')
                        for g in json.loads(p.read_text())['per_game']}
        print('missing', name); return {}
    fps = json.load(open(a.fp)) if getattr(a, 'fp', None) else None
    base = load(a.base or a.runs.format(K=0))
    res = {k: load(a.runs.format(K=k)) for k in rng_list(a.vars)}
    eng = mapio.new_engine(); rows = []; won = sum(base.values()); fixed = 0
    for (mp, side), w in sorted(base.items()):
        if w: continue
        k = next((k for k, r in res.items() if r.get((mp, side))), None)
        if k is None: continue
        m = mapio.read_map(eng, (ROOT / 'maps/ladder-pool' / f'{mp}.map26a').read_bytes())
        fp = fps.get(f'{mp}-{side}') if fps else None
        if fp:  # the fingerprint the bot itself printed for this map and side (exact)
            rows.append(f"    {fp[0]}, {fp[1]}, {fp[2]}, {fp[3]}, {fp[4]}, {k}, // {mp} {side}")
        else:
            n_full, gems = full_groups(m)
            rows.append(f"    {m['w']}, {m['h']}, {n_full}, {gems}, {(0 if side == 'A' else 1) ^ a.swap}, {k}, // {mp} {side}")
        fixed += 1
    write_header(rows)
    print(f'base {won}/{len(base)}; counter rows {fixed}; expected {won + fixed}/{len(base)}')


def robust(a):
    """Multi-opponent counter table (see the module doc)."""
    def load(name):
        for d in a.run_dirs.split(','):
            for p in (ROOT / d / name / 'results.json', ROOT / d / f'{name}.json'):
                if p.exists():
                    return {(g['map'], g['side']): g['outcome'] == ('teamA' if g['side'] == 'A' else 'teamB')
                            for g in json.loads(p.read_text())['per_game']}
        return None
    opps, ks = a.opps.split(','), rng_list(a.vars)
    res = {(o, k): load(a.runs.format(OPP=o, K=k)) for o in opps for k in ks}
    miss = [f'{o}-k{k}' for (o, k), v in res.items() if v is None]
    if miss: print('missing runs:', ' '.join(miss))
    have = {o: [k for k in ks if res[o, k] is not None] for o in opps}
    if any(0 not in have[o] for o in opps): sys.exit('variant 0 must be present for every opponent')
    cells = sorted(res[opps[0], 0])
    def pick(use):
        out = {}
        for c in cells:
            score = {k: sum(res[o, k].get(c, False) for o in use) for k in ks if all(res[o, k] is not None for o in use)}
            best = max(score, key=lambda k: (score[k], -k))
            out[c] = best if score[best] >= score[0] + a.margin else 0
        return out
    choice = pick(opps)
    for o in opps:
        base = sum(res[o, 0].values()); got = sum(res[o, choice[c]].get(c, False) for c in cells)
        lo = pick([x for x in opps if x != o]) if len(opps) > 1 else choice
        held = sum(res[o, lo[c]].get(c, False) for c in cells)
        print(f'{o:8s} variant 0 {base:3d}/{len(cells)}  table {got:3d}  (+{got - base})  left-out estimate {held:3d} ({held - base:+d})')
    print('cells switched:', sum(k != 0 for k in choice.values()), 'of', len(cells))
    if a.write:
        fps = json.load(open(a.fp)); rows = []
        for (mp, side), k in choice.items():
            if k == 0: continue
            fp = fps[f'{mp}-{side}']
            rows.append(f"    {fp[0]}, {fp[1]}, {fp[2]}, {fp[3]}, {fp[4]}, {k}, // {mp} {side}")
        if len(rows) > MAX_ROWS: sys.exit(f'{len(rows)} rows > {MAX_ROWS}')
        write_header(rows); print('wrote', len(rows), 'rows to', HDR)


if __name__ == '__main__':
    main()
