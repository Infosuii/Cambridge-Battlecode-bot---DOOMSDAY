"""Meta compiler, step 2: fit the top teams' decisions from a crawl and write a C++ header for the bot.

Today's tables (research/v62/BIG_STRATEGIES.md, section 6): the winning item opening and stat-stack ratio for each
hero, and draft pick/win counts in top-vs-top games. Re-run after each crawl; the header carries a data stamp, so a
release is reproducible from its own source.

  python tools/meta/compile.py <crawl dir> [<crawl dir> ...] --out bots/v66/src/meta_tables.h [--report R.md]
"""
import argparse
import collections as co
import json
from pathlib import Path
import statistics as st

DRAFT = ['ryth', 'vesper_vale', 'vendetta', 'cassi_and_issac', 'stellar', 'prism', 'marcella', 'tavi', 'willow', 'ren',
         'varg', 'heart_of_ruin']  # bc::champion_draft order (sdk/cpp/cambc.h)
OPEN_BY = 600  # opening = shards bought by this round
STACK_FROM = 600


def snake(name):
    return name.strip().lower().replace(' & ', '_and_').replace(' ', '_')


def read(p):
    return json.loads(Path(p).read_text(encoding='utf-8-sig'))


def purchases(d, champ):
    out = []
    for e in d['events']:
        if e['kind'] != 'buyItem' or e['owner'].get('team') != champ['team'] or e['owner'].get('id') != champ['id']:
            continue
        for x in e['entries']:
            name = x['target']['name']
            if 'Shard' in name:  # emblems form from five shards; only shard purchases are decisions
                out.append((int(x['timestamp']['round']), snake(name), float(x.get('value', 1))))
    return sorted(out)


def fit_items(summaries):
    by_hero = co.defaultdict(list)
    for d in summaries:
        win = d['match'].get('outcome')
        for c in d['champions']:
            if c['team'] == win:
                by_hero[snake(c['name'])].append(purchases(d, c))
    builds = {}
    for hero, seqs in sorted(by_hero.items()):
        n = len(seqs)
        if n < 15:
            continue
        early, first, late = co.Counter(), co.defaultdict(list), co.Counter()
        for s in seqs:
            seen = set()
            for rd, item, v in s:
                if rd <= OPEN_BY:
                    early[item] += v
                    if item not in seen:
                        first[item].append(rd)
                        seen.add(item)
                if rd > STACK_FROM:
                    late[item] += v
        # Opening: non-Bruiser items the winners buy at least 1.5 shards of by OPEN_BY, in order of first purchase;
        # one 5-shard emblem each (two when they average 6+). Bruiser bought early also goes in, at its median order.
        cand = [(st.median(first[i]), i, early[i] / n) for i in early if early[i] / n >= 1.5]
        cand.sort()
        opening = [(i, 10 if per >= 6 else 5) for _, i, per in cand[:4]]
        # Stacks: the most-bought non-health shard after STACK_FROM, and the most-bought health shard; ratio = main
        # emblems per health emblem.
        main = max((i for i in late if not i.endswith('_of_health')), key=lambda i: late[i], default=None)
        health = max((i for i in late if i.endswith('_of_health')), key=lambda i: late[i], default=None)
        if main is None:
            main = 'bruiser_shard_of_strength'
        if health is None:
            health = 'bruiser_shard_of_health'
        ratio = late[main] / max(1.0, late[health])
        per_health = max(1, min(4, round(ratio)))
        builds[hero] = dict(apps=n, opening=opening, main=main, health=health, per_health=per_health,
                            early={i: round(early[i] / n, 2) for i, _ in early.most_common(8)},
                            late={i: round(late[i] / n, 2) for i, _ in late.most_common(6)})
    return builds


def fit_draft(matches):
    games, wins = co.Counter(), co.Counter()
    for m in matches:
        for t in m['teams']:
            for p in t.get('draftPicks') or []:
                games[p] += 1
                wins[p] += t['result'] == 'win'
    return {DRAFT[k]: dict(games=games[k], wins=wins[k]) for k in range(len(DRAFT))}


def emit(builds, draft, stamp, path):
    L = ['// Generated by tools/meta/compile.py from top-12 vs top-12 ranked games; do not edit by hand.',
         f'// Data: {stamp}', '#pragma once', '#include <cambc.h>', '', 'namespace meta {',
         f'inline constexpr const char* kStamp = "{stamp}";', '',
         'struct Step {', '    bc::item_type item;', '    int total;', '};',
         'struct Build {', '    int apps;    // winning appearances behind the row', '    int n_open;',
         '    Step open[4];', '    bc::item_type main, health; // stat stacks after the opening',
         '    int per_health;              // main-stat emblems per health emblem', '};', '',
         '// The winners\' build for a hero, or nullptr when the sample is too small.',
         'inline const Build* build_for(bc::champion_type t) {', '    using it = bc::item_type;',
         '    switch (t) {']
    for hero, b in builds.items():
        steps = ', '.join(f'{{it::{i}, {n}}}' for i, n in b['opening'])
        pad = ', '.join(['{it::bruiser_shard_of_health, 0}'] * (4 - len(b['opening'])))
        allsteps = ', '.join(x for x in [steps, pad] if x)
        L.append(f'    case bc::champion_type::{hero}: {{ // {b["apps"]} winning appearances')
        L.append(f'        static constexpr Build b{{{b["apps"]}, {len(b["opening"])}, {{{allsteps}}}, it::{b["main"]}, '
                 f'it::{b["health"]}, {b["per_health"]}}};')
        L.append('        return &b;')
        L.append('    }')
    L += ['    default:', '        return nullptr;', '    }', '}', '',
          '// Draft: games and wins per pick (bc::champion_draft order) in the same top-vs-top games.']
    L.append('inline constexpr int kDraftGames[12] = {' + ', '.join(str(draft[h]['games']) for h in DRAFT) + '};')
    L.append('inline constexpr int kDraftWins[12] = {' + ', '.join(str(draft[h]['wins']) for h in DRAFT) + '};')
    L += ['} // namespace meta', '']
    Path(path).write_text('\n'.join(L), encoding='utf8')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('crawls', nargs='+')
    ap.add_argument('--out', required=True)
    ap.add_argument('--report')
    a = ap.parse_args()
    summaries, matches, stamps = [], {}, []
    for c in map(Path, a.crawls):
        info = read(c / 'crawl.json')
        stamps.append(f"{info['since']}..{info['crawledAt'][:19]} top{info['top']}")
        for m in read(c / 'matches.json'):
            matches[m['matchId']] = m
        for p in sorted((c / 'summaries').glob('*.json')):
            try:
                d = read(p)
            except ValueError:
                continue
            if d['match'].get('engineVersion') == '2.0.0':
                summaries.append(d)
    builds = fit_items(summaries)
    draft = fit_draft(matches.values())
    stamp = f"{'; '.join(stamps)}; {len(matches)} games, {len(summaries)} summaries"
    emit(builds, draft, stamp, a.out)
    if a.report:
        R = [f'# Meta tables ({stamp})', '', '## Items (winners)', '',
             '| Hero | Winning apps | Opening (by round 600) | Stacks | Mean shards by R600 | After R600 |', '|---|---:|---|---|---|---|']
        for h, b in builds.items():
            R.append(f"| {h} | {b['apps']} | {' > '.join(f'{i} x{n}' for i, n in b['opening'])} | {b['main']} : {b['health']} = {b['per_health']}:1 | "
                     f"{', '.join(f'{k} {v}' for k, v in b['early'].items())} | {', '.join(f'{k} {v}' for k, v in b['late'].items())} |")
        R += ['', '## Draft (top-vs-top)', '', '| Pick | Games | Win rate |', '|---|---:|---:|']
        for h in sorted(DRAFT, key=lambda h: -draft[h]['games']):
            g = draft[h]['games']
            R.append(f"| {h} | {g} | {draft[h]['wins'] / g:.3f} |" if g else f'| {h} | 0 | - |')
        Path(a.report).write_text('\n'.join(R) + '\n', encoding='utf8')
    print('wrote', a.out, len(builds), 'heroes;', stamp)


if __name__ == '__main__':
    main()
