"""Generate bot/src/nn_config.h for a profile (agent B; CONTRACTS 3.1).

    python tools/gen_config.py --profile teacher_exact            # writes bot/src/nn_config.h
    python tools/gen_config.py --profile release --src <dir> --stdout

Head modes come from the same plan as tools/install_models.py (profile + models/registry.json + current schemas),
so a head is only ever on when a compatible model with an allowed lifecycle status exists. Prefer
tools/install_models.py, which regenerates nn_config.h, nn_registry.h and nn_weights_*.h together.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'python'))

from nfs import registry  # noqa: E402
from nfs.models.config import HEAD_NAMES  # noqa: E402

MODE_CPP = {'off': 'Mode::off', 'shadow': 'Mode::shadow', 'active': 'Mode::active'}


def render(profile: dict, plan: dict) -> str:
    modes = [plan['heads'][h]['mode'] for h in HEAD_NAMES]
    any_head = any(m != 'off' for m in modes)
    # Flags that only make sense with a head running are forced off otherwise (nothing to log / test / credit).
    training = bool(profile['training']) and any_head
    telemetry = bool(profile['telemetry']) and any_head
    credit = bool(profile['fuel_credit']) and any_head
    selftest = bool(profile['selftest']) and any_head
    strip = bool(profile['strip_lab'])
    b = lambda v: 'true' if v else 'false'  # noqa: E731
    lines = [
        f'// GENERATED by tools/gen_config.py --profile {profile["name"]} - do not edit; switch with tools/install_models.py.',
        '// ' + profile.get('description', '').replace('\n', ' '),
        '// API: CONTRACTS.md section 3.1. Mode off = compiled out; shadow = run + record, teacher executes;',
        '// active = network choice executes (argmax; sampled when kTraining).',
        '#pragma once',
        '#include <cstdint>',
        '',
        f'#define NN_ANY_HEAD {int(any_head)}',
        f'#define NN_STRIP_LAB {int(strip)}',
        f'#define NN_TRAINING {int(training)}',
        f'#define NN_TELEMETRY {int(telemetry)}',
        '',
        'namespace nncfg {',
        'enum class Mode : int { off = 0, shadow = 1, active = 2 };',
        'enum class H : int { ' + ', '.join(HEAD_NAMES) + ', count };',
        'inline constexpr Mode kMode[static_cast<int>(H::count)] = {',
        *[f'    {MODE_CPP[m]},{" " * (14 - len(MODE_CPP[m]))}// {h}' + (f' ({plan["heads"][h]["model"]})'
                                                                       if plan['heads'][h]['model'] else '')
          for h, m in zip(HEAD_NAMES, modes)],
        '};',
        'constexpr Mode mode(H h) { return kMode[static_cast<int>(h)]; }',
        f'inline constexpr bool kAnyHead = {b(any_head)};',
        f'inline constexpr bool kTraining = {b(training)};',
        f'inline constexpr bool kTelemetry = {b(telemetry)};',
        f'inline constexpr bool kFuelCredit = {b(credit)};',
        f'inline constexpr bool kSelfTest = {b(selftest)};',
        f'inline constexpr bool kStripLab = {b(strip)};',
        f'inline constexpr unsigned kSeed = {int(profile["seed"]) & 0xFFFFFFFF}u;',
        f'inline constexpr const char* kProfile = "{profile["name"]}";',
        '} // namespace nncfg',
        '',
    ]
    return '\n'.join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--profile', required=True)
    ap.add_argument('--src', default=str(ROOT / 'bot/src'), help='target source tree (schemas are read from it)')
    ap.add_argument('--out', default=None, help='output path (default <src>/nn_config.h)')
    ap.add_argument('--stdout', action='store_true')
    a = ap.parse_args(argv)
    prof = registry.load_profile(a.profile, ROOT)
    plan = registry.resolve_profile(prof, registry.load_registry(ROOT), ROOT, Path(a.src))
    text = render(prof, plan)
    if a.stdout:
        sys.stdout.write(text)
        return 0
    out = Path(a.out) if a.out else Path(a.src) / 'nn_config.h'
    out.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {out} (profile {prof["name"]}, heads on: '
          f'{[h for h in HEAD_NAMES if plan["heads"][h]["mode"] != "off"]})')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
