"""Compile coordinated opening examples from winning replays, without local result selection."""
from collections import Counter
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools/proxy'))
from compile_proxy import milestones, DRAFT, snake


def main():
    index=json.loads((ROOT/'artifacts/local-only/proxy/replays/index.json').read_text())
    evidence=json.loads((ROOT/'research/v67/MAPS.json').read_text())
    keys=json.loads((ROOT/'research/proxy/map_keys.json').read_text())
    keys={k.replace('_','-'):v for k,v in keys.items()}
    heroes=['ryth','vesper_vale','vendetta','cassi','issac','stellar','prism','marcella','willow','ren','varg','tavi','heart_of_ruin']
    starts=['// Generated by tools/v67/compile_plans.py from winning engine-2 replay openings.',
            '#pragma once','#include <cambc.h>','namespace plan67 {',
            'struct Route { bc::champion_type hero; unsigned n; int groups[12]; };',
            'struct Item { bc::champion_type hero; unsigned n; bc::item_type items[4]; int totals[4]; };',
            'struct Plan { unsigned key,n; bc::champion_draft picks[6]; int sx,sy; unsigned nr; Route routes[6]; unsigned ni; Item items[6]; };',
            'inline constexpr Plan kPlans[] = {']
    selected=[]
    for mp,data in evidence.items():
        examples=data['examples']
        if not examples: continue
        # Prefer a lineup supported by repeated crawl wins; choose an intact team's
        # opening, never stitch incompatible independent hero routes together.
        def lineup(ex):
            return tuple((3 if a['type'] in (3,4) else DRAFT.index(heroes[a['type']])) for a in ex['actors'] if a['type']!=4)
        counts=Counter(lineup(ex) for ex in examples)
        ranked={tuple(d['picks']):(d['wins']+1)/(d['games']+2)*min(1,d['games']/4) for d in data['drafts']}
        supported=[seq for seq in counts if seq in ranked]
        draft=max(supported,key=lambda seq:ranked[seq]) if supported else counts.most_common(1)[0][0]
        pool=[ex for ex in examples if lineup(ex)==draft]
        def score(ex):
            return sum(c['gold']+c['gems']*2 for a in ex['actors'] for c in a['capture'])
        ex=max(pool,key=score)
        summary=None
        for directory in ['artifacts/local-only/meta/20261027/summaries','artifacts/local-only/duels']:
            p=ROOT/directory/(ex['match']+'.json')
            if p.exists(): summary=json.loads(p.read_text(encoding='utf-8-sig')); break
        routes=[]
        for a in ex['actors']:
            seq=[x['group'] for x in a['route'][:12]]
            routes.append('{bc::champion_type::'+heroes[a['type']]+', '+str(len(seq))+', {'+','.join(map(str,seq))+'}}')
        items=[]
        if summary:
            for a in ex['actors']:
                ch=next((c for c in summary['champions'] if c['id']==a['id'] and c['team']=='team'+ex['winner'].upper()),None)
                if not ch: continue
                seq=milestones(summary,ch['team'],ch['id'])[:4]
                if seq: items.append('{bc::champion_type::'+heroes[a['type']]+', '+str(len(seq))+', {'+','.join('bc::item_type::'+s[0] for s in seq)+'}, {'+','.join(str(s[1]) for s in seq)+'}}')
        sp=ex['actors'][0]['spawn']
        starts.append('    // '+mp+' winner '+ex['match']+' side '+ex['winner'])
        starts.append('    {'+str(keys[mp]['key'])+'u, '+str(len(draft))+', {'+','.join('bc::champion_draft::'+DRAFT[i] for i in draft)+'}, '+str(sp['x'])+','+str(sp['y'])+', '+str(len(routes))+', {'+','.join(routes)+'}, '+str(len(items))+', {'+','.join(items)+'}},')
        selected.append(dict(map=mp,match=ex['match'],side=ex['winner'],picks=list(draft),opening_income_score=score(ex),route_heroes=len(routes),item_heroes=len(items)))
    starts+=['};','}']
    (ROOT/'bots/v67/src/map_plans.h').write_text('\n'.join(starts)+'\n',encoding='utf8',newline='\n')
    (ROOT/'research/v67/OPENINGS.json').write_text(json.dumps(selected,indent=1)+'\n',encoding='utf8',newline='\n')
    print('compiled',len(selected),'coherent winning-team opening examples')


if __name__=='__main__': main()
