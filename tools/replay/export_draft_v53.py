"""Export the fitted v53 model into draft-only C++; specify the maps to enable."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
SIGNATURES={'00elkring':(30,30,5,10),'01yellow-brick-road':(30,40,5,28),'00swirl':(30,45,4,22),
            '01boss-battle':(41,50,5,31),'01concentrated-wealth':(61,61,5,11)}

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--model',type=Path,default=ROOT/'artifacts/local-only/v53-draft/model.json')
    p.add_argument('--out',type=Path,default=ROOT/'bots/v53/src/draft_v53.h')
    p.add_argument('--maps',nargs='+',choices=list(SIGNATURES),required=True)
    a=p.parse_args();d=json.loads(a.model.read_text());w=d['weights'];maps=d['maps'];nm=len(maps)
    def f(x):
        s=format(x,'.9g');return s+('f' if '.' in s or 'e' in s else '.0f')
    matrix=[[0.0]*12 for _ in range(12)];at=12+nm*12
    for i in range(12):
        for j in range(i+1,12):matrix[i][j]=w[at];matrix[j][i]=-w[at];at+=1
    out=['// Generated by tools/replay/export_draft_v53.py. Offline weights; draft phase only.',
         '// 243,904 games, team-pair-disjoint held-out test; see artifacts/claude_ops/V53_DRAFT_REPORT.json.',
         '#pragma once','namespace v53draft {','struct Key { int w,h,size,groups; float pick[12]; };','inline constexpr Key keys[] = {']
    for name in a.maps:
        sig=SIGNATURES[name];idx=maps.index(list(sig[:3]));coef=[w[i]+w[12+idx*12+i] for i in range(12)]
        out.append('    {'+','.join(map(str,sig))+', {'+','.join(map(f,coef))+'}}, // '+name)
    out+=['};','inline constexpr float counter[12][12] = {']
    out+=['    {'+','.join(map(f,row))+'},' for row in matrix]
    out+=['};', '''inline bool pick(unsigned size, const std::vector<bc::champion_draft>& chosen) {
    const int w=std::min(bc::map::width(),bc::map::height());
    const int h=std::max(bc::map::width(),bc::map::height());
    const Key* found=nullptr;
    for (const auto& k:keys) if(k.w==w && k.h==h && k.size==static_cast<int>(size)) found=&k;
    if(!found) return false;
    std::uint32_t groups=0;
    if(bc::detail::sdk_map_num_camp_groups(&groups)!=0 || static_cast<int>(groups)!=found->groups) return false;
    const auto theirs=bc::draft::current_draft(team::enemy);
    int best=-1; float value=-1e30f;
    for(int c=0;c<12;++c) {
        const auto choice=static_cast<bc::champion_draft>(c);
        if(std::find(chosen.begin(),chosen.end(),choice)!=chosen.end()) continue;
        float score=found->pick[c];
        for(auto enemy:theirs) {
            const int e=static_cast<int>(enemy);
            if(e>=0 && e<12) score+=counter[c][e];
        }
        if(score>value) {value=score;best=c;}
    }
    if(best<0) return false;
    bc::draft::pick(static_cast<bc::champion_draft>(best));
    return true;
}
} // namespace v53draft''']
    a.out.write_text('\n'.join(out)+'\n',encoding='utf8')
    print(a.out)

if __name__=='__main__':main()
