// Semantic edge cases identified before examined trajectories are processed.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {episodes,isIdle,unionTurns,equip,isMovementAction} from './detectors.mjs';
const row=r=>({r,complete:true,alive:true,end_alive:true,p:{x:4,y:4},end_p:{x:4,y:4},channel:0,end_channel:0,stun:false,capture:false,actions:[]});
const run=rows=>{const ch={detectors:{D1:{events:[]}}};episodes(ch,'D1','stationary',rows,isIdle,10,()=>({}),r=>r.p.x+','+r.p.y);return ch.detectors.D1.events;};
const rows=Array.from({length:20},(_,i)=>row(i+1));
assert.equal(run(rows).length,1);assert.equal(run(rows)[0].fired_round,10);
assert.equal(run(rows.slice(0,9)).length,0);
const gap=Array.from({length:10},(_,i)=>row(i+1));gap[5].r=20;
assert.equal(run(gap).length,0,'Missing turns must break an episode');
const knockback=Array.from({length:10},(_,i)=>row(i+1));knockback[5].end_p={x:5,y:4};
assert.equal(run(knockback).length,0,'Passive movement must not be called stationary');
const channel=Array.from({length:10},(_,i)=>row(i+1));channel[9].actions=[{kind:12}];
assert.equal(run(channel).length,0,'A bank start must interrupt a stationary episode');
const attack=Array.from({length:10},(_,i)=>row(i+1));attack[9].actions=[{kind:5}];
assert.equal(run(attack).length,0,'Attacks break idle runs');
const death=Array.from({length:10},(_,i)=>row(i+1));death[9].end_alive=false;
assert.equal(run(death).length,0,'Dying during the observed interval censors it');
const censored=Array.from({length:10},(_,i)=>row(i+1));censored[9].complete=false;
assert.equal(run(censored).length,0,'An incomplete final turn must not complete a run');
const capture=Array.from({length:10},(_,i)=>row(i+1));capture[9].capture=true;
assert.equal(run(capture).length,0,'Capture occupation is excluded');
const stunned=Array.from({length:10},(_,i)=>row(i+1));stunned[9].stun=true;
assert.equal(run(stunned).length,0,'Stuns are excluded');
assert.equal(unionTurns([{start:1,end:10,turns:10},{start:6,end:15,turns:10}]),15,'Overlapping subtypes must not duplicate turns');
const inventory=new Array(84).fill(0);inventory[12*6+1]=1;assert.equal(equip(inventory),750,'Greed is a 25-shard emblem');
const script=fileURLToPath(new URL('./detectors.mjs',import.meta.url));
const root=path.resolve(path.dirname(script),'../..');
const forbidden=path.join(root,'artifacts/tmp/holdout-guard-probe-'+Date.now());
const probe=spawnSync(process.execPath,[script,'--partition','hands-off','--out',forbidden],{env:{...process.env,NFS_REPLAY_ENGINE:'2.0.0'},encoding:'utf8'});
assert.notEqual(probe.status,0);assert.match(probe.stderr,/Only calibration\/examined partitions are allowed/);
assert.equal(fs.existsSync(forbidden),false,'Held-out refusal must occur before creating output');
assert.equal(isMovementAction({kind:23,from:{x:4,y:4},to:{x:5,y:4}}),false,'Movement-blocked destinations are not arrivals');
assert.equal(isMovementAction({kind:22,from:{x:4,y:4},to:{x:15,y:14}}),true,'Teleport completion is actual movement');
console.log(JSON.stringify({semantic_cases_passed:15,hands_off_guard_passed:true}));
