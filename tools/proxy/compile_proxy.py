"""Proxy opponent: the top teams' drafts and item purchases as a C++ header for bots/proxy (proxy_tables.h).

  python tools/proxy/compile_proxy.py empty --out bots/proxy/src/proxy_tables.h
      An empty table (every team falls back to the normal draft and items); used to read the map keys.
  python tools/proxy/compile_proxy.py mapkeys --bot bots/proxy --out research/proxy/map_keys.json [--workers 16]
      Plays each pool map once with a PROXY_PRINT_MAPID build and records the draft-table key both sides print.
  python tools/proxy/compile_proxy.py tables --crawl <meta crawl dir> --arms research/proxy/ladder_arms.json
         --keys research/proxy/map_keys.json --out bots/proxy/src/proxy_tables.h --report research/proxy/TABLES.md
      Per top team (and pooled, team -1): the lineup it drafts on each map (the most common pick sequence there, from
      its engine-2 games in the crawls and its games against us in the duel), its overall pick order for maps
      without data, and per hero its purchase milestones (each time a shard's running count reaches a multiple of 5):
      the most common first four milestones, then the most common item after them and the most common health item
      after them, in their proportion. Teams whose recall-start share in contact (--style, from style_report.py)
      exceeds 0.5 get perma_recall.
Team order is the plan's opponents sorted by name; bots/proxy_<k> builds use PROXY_TEAM k (research/proxy/README.md).
"""
import argparse
import collections as co
import concurrent.futures as cf
import json
from pathlib import Path
import re
import shutil
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'python'))
sys.path.insert(0, str(ROOT / 'tools/proxy'))

DRAFT = ['ryth', 'vesper_vale', 'vendetta', 'cassi_and_issac', 'stellar', 'prism', 'marcella', 'tavi', 'willow', 'ren',
         'varg', 'heart_of_ruin']  # bc::champion_draft order (sdk/cpp/cambc.h)
OPEN = 4  # opening milestones


def snake(name):
    return name.strip().lower().replace(' & ', '_and_').replace(' ', '_')


def read(p):
    return json.loads(Path(p).read_text(encoding='utf-8-sig'))


def teams_of_plan(plan_path):
    return sorted({g['opponent'] for g in read(plan_path)['groups']})


HEADER = '''// Generated by tools/proxy/compile_proxy.py; do not edit by hand.
// Data: {stamp}
#pragma once
#include <cambc.h>
#include <cstdint>

namespace proxy {{
struct Step {{
    bc::item_type item;
    int total; // shards of the item owned (emblems count as their shards)
}};
struct Items {{ // one hero's purchases
    bc::champion_type hero;
    int apps; // appearances behind the row
    int n_open;
    Step open[{open}];
    bc::item_type main, health; // stacks after the opening: per_health main emblems per health emblem (0 = no health)
    int per_health;
}};
struct MapPicks {{
    std::uint32_t key; // draft.cpp proxy_map_key
    int n;
    bc::champion_draft picks[6];
}};
struct Team {{
    const char* name;
    int n_maps;
    const MapPicks* maps;
    int n_fallback;
    bc::champion_draft fallback[12];
    int n_items;
    const Items* items;
    bool perma_recall; // starts a recall at the end of every turn and cancels it next turn (PROXY_PERMA_RECALL)
}};
'''


def emit(path, stamp, teams):
    """teams: [(name, maps[(key, picks, games, map)], fallback[...], items{hero: dict}, perma_recall)], index 0 = pooled
    (PROXY_TEAM -1)."""
    L = [HEADER.format(stamp=stamp, open=OPEN)]
    for k, (name, maps, fallback, items, perma) in enumerate(teams):
        if maps:
            L.append(f'inline constexpr MapPicks kMaps{k}[] = {{ // {name}')
            for key, picks, games, map_name in maps:
                L.append(f'    {{{key}u, {len(picks)}, {{' + ', '.join(f'bc::champion_draft::{p}' for p in picks) + f'}}}}, // {map_name}: {games} games')
            L.append('};')
        if items:
            L.append(f'inline constexpr Items kItems{k}[] = {{ // {name}')
            for hero, b in items.items():
                steps = [f'{{bc::item_type::{i}, {n}}}' for i, n in b['open']]
                steps += ['{bc::item_type::bruiser_shard_of_health, 0}'] * (OPEN - len(steps))
                L.append(f'    {{bc::champion_type::{hero}, {b["apps"]}, {len(b["open"])}, {{{", ".join(steps)}}}, '
                         f'bc::item_type::{b["main"]}, bc::item_type::{b["health"]}, {b["per_health"]}}},')
            L.append('};')
    L.append(f'inline constexpr Team kTeams[{len(teams)}] = {{')
    for k, (name, maps, fallback, items, perma) in enumerate(teams):
        fb = ', '.join(f'bc::champion_draft::{p}' for p in fallback) or 'bc::champion_draft::ryth'
        L.append(f'    {{"{name}", {len(maps)}, {f"kMaps{k}" if maps else "nullptr"}, {len(fallback)}, {{{fb}}}, '
                 f'{len(items)}, {f"kItems{k}" if items else "nullptr"}, {"true" if perma else "false"}}},')
    L += ['};', '} // namespace proxy', '']
    Path(path).write_text('\n'.join(L), encoding='utf8', newline='\n')


def cmd_empty(a):
    names = ['top'] + teams_of_plan(a.plan)
    emit(a.out, 'empty (no tables)', [(n, [], [], {}, False) for n in names])
    print('wrote', a.out, len(names), 'empty teams')


def cmd_mapkeys(a):
    import zipfile
    from nfs import engine
    import local_duel
    maps = sorted(p.stem.replace('-', '_') for p in local_duel.MAPS.glob('*.map26a'))
    work = ROOT / 'artifacts/tmp/proxy-mapkeys'
    if work.exists():
        shutil.rmtree(work, ignore_errors=True)
    (work / 'bot').mkdir(parents=True)
    shutil.copytree(Path(a.bot) / 'src', work / 'bot/src', copy_function=shutil.copyfile)
    common = work / 'bot/src/common.h'
    text = common.read_bytes().decode('utf8')
    text, n = re.subn(r'#define PROXY_PRINT_MAPID 0', '#define PROXY_PRINT_MAPID 1', text)
    if n != 1:
        raise SystemExit('no PROXY_PRINT_MAPID line')
    common.write_bytes(text.encode('utf8'))
    wasm = local_duel.build(work / 'bot', 1, work, 'mapid')

    def one(m):
        folder = work / 'games' / m
        engine.run_match(wasm, wasm, local_duel.map_path(m), folder)
        keys = []
        for side in 'ab':
            out = engine.team_stdout(folder, side)
            found = set(re.findall(r'PROXYMAP (\d+) (\d+) (\d+) (\d+)', out))
            if len(found) != 1:
                raise RuntimeError(f'{m} side {side}: {found}')
            keys.append(found.pop())
        if keys[0] != keys[1]:
            raise RuntimeError(f'{m}: sides disagree {keys}')
        key, w, h, size = map(int, keys[0])
        return m, dict(key=key, width=w, height=h, size=size)

    out = {}
    with cf.ThreadPoolExecutor(max_workers=a.workers) as ex:
        for m, v in ex.map(one, maps):
            out[m] = v
    by_key = co.defaultdict(list)
    for m, v in out.items():
        by_key[v['key']].append(m)
    clash = {k: v for k, v in by_key.items() if len(v) > 1}
    if clash:
        raise SystemExit(f'map keys collide: {clash}')
    Path(a.out).write_text(json.dumps(out, indent=1) + '\n', encoding='utf8', newline='\n')
    print('wrote', a.out, len(out), 'maps, all keys distinct, both sides agree')


def milestones(d, team, cid):
    """[(item, total)] each time a shard's running count reaches a multiple of 5, in purchase order."""
    run, out = co.Counter(), []
    for e in d['events']:
        if e['kind'] != 'buyItem' or e['owner'].get('team') != team or e['owner'].get('id') != cid:
            continue
        for x in sorted(e['entries'], key=lambda x: int(x['timestamp']['round'])):
            name = x['target']['name']
            if 'Shard' not in name:
                continue
            item = snake(name)
            before = run[item]
            run[item] += int(float(x.get('value', 1)))
            for t in range(5 * (before // 5 + 1), run[item] + 1, 5):
                out.append((item, t))
    return out


def fit_items(seqs):
    """seqs: one milestone list per appearance of a hero."""
    n = len(seqs)
    k = OPEN
    while k > 1 and sum(len(s) >= k for s in seqs) < max(5, n // 3):
        k -= 1
    heads = co.Counter(tuple(s[:k]) for s in seqs if len(s) >= k)
    if not heads:
        return None
    opening = list(heads.most_common(1)[0][0])
    after = co.Counter(item for s in seqs if tuple(s[:k]) == tuple(opening) for item, _ in s[k:])
    if not after:
        after = co.Counter(item for s in seqs for item, _ in s[k:])
    main = after.most_common(1)[0][0] if after else 'bruiser_shard_of_strength'
    health = [(c, i) for i, c in after.items() if i.endswith('_of_health') and i != main]
    health_item, health_n = (max(health)[1], max(health)[0]) if health else ('bruiser_shard_of_health', 0)
    per_health = 0 if health_n == 0 or health_n * 10 < after[main] else max(1, min(6, round(after[main] / health_n)))
    return dict(apps=n, open=opening, main=main, health=health_item, per_health=per_health,
                agree=heads.most_common(1)[0][1] / sum(heads.values()))


def cmd_tables(a):
    names = teams_of_plan(a.plan)
    keys = read(a.keys)
    # Perma-recall: the share of contact rounds in which the team started a recall (tools/proxy/style_report.py), in
    # its games against us (opp:) and against other top teams (team:). Teams that do it do it nearly always (> 0.85).
    style = read(a.style)
    recall = {n: max(style.get(f'{c}:{n}', {}).get('recall_start|contact', 0.0) for c in ('opp', 'team')) for n in names}
    # Drafts: the crawl's top-vs-top listings and every duel game against us.
    seqs = co.defaultdict(lambda: co.defaultdict(co.Counter))  # team -> map -> ordered picks -> games
    for c in a.crawl:
        for m in read(Path(c) / 'matches.json'):
            for t in m['teams']:
                if t.get('draftPicks') and t['name'] in names and t.get('engineVersion') == '2.0.0' and m['status'] == 'finished':
                    seqs[t['name']][m['map']][tuple(t['draftPicks'])] += 1
    arms = read(a.arms)['games']
    for r in arms:
        if r.get('theirPicks'):
            seqs[r['opponent']][r['map']][tuple(r['theirPicks'])] += 1
    # Items: crawl summaries (sides from the listing) and the duel summaries (the side that is not ours).
    side_names = {}
    for c in a.crawl:
        for m in read(Path(c) / 'matches.json'):
            side_names[m['matchId']] = {('team' + t['side'].upper()): t['name'] for t in m['teams']}
    sources = []
    for c in a.crawl:
        sources += [(p, side_names.get(p.stem)) for p in sorted((Path(c) / 'summaries').glob('*.json'))]
    seen_duel = set()
    for r in arms:
        if r['matchId'] in seen_duel:
            continue
        seen_duel.add(r['matchId'])
        them = 'teamB' if r['side'] == 'a' else 'teamA'
        sources.append((ROOT / 'artifacts/local-only/duels' / f"{r['matchId']}.json", {them: r['opponent']}))
    buys = co.defaultdict(lambda: co.defaultdict(list))  # team -> hero -> milestone lists
    used = 0
    for p, who in sources:
        if not who or not p.exists():
            continue
        try:
            d = read(p)
        except ValueError:
            continue
        if d['match'].get('engineVersion') != '2.0.0':
            continue
        used += 1
        for ch in d['champions']:
            team = who.get(ch['team'])
            if team in names:
                buys[team][snake(ch['name'])].append(milestones(d, ch['team'], ch['id']))
    teams, report = [], []
    for label in ['top'] + names:
        members = names if label == 'top' else [label]
        per_map = co.defaultdict(co.Counter)
        for t in members:
            for m, c in seqs[t].items():
                per_map[m].update(c)
        maps = []
        for m, c in sorted(per_map.items()):
            if m not in keys:
                continue
            picks, g = c.most_common(1)[0]
            maps.append((keys[m]['key'], [DRAFT[i] for i in picks], g, m))
        rank = co.defaultdict(list)
        for m, c in per_map.items():
            for picks, g in c.items():
                for i, p in enumerate(picks):
                    rank[DRAFT[p]].append((i, g))
        total = sum(g for c in per_map.values() for g in c.values())
        score = {h: (sum(i * g for i, g in v) + 6 * (total - sum(g for _, g in v))) / max(1, total) for h, v in rank.items()}
        fallback = sorted(score, key=lambda h: score[h])
        hero_seqs = co.defaultdict(list)
        for t in members:
            for h, s in buys[t].items():
                hero_seqs[h] += s
        items = {}
        for h, s in sorted(hero_seqs.items()):
            if len(s) >= 5:
                b = fit_items(s)
                if b:
                    items[h] = b
        perma = label != 'top' and recall[label] > 0.5
        teams.append((label, maps, fallback, items, perma))
        modal = sum(c.most_common(1)[0][1] for c in per_map.values()) / max(1, total)
        report.append((label, len(maps), total, modal, fallback, items, recall.get(label, 0.0)))
    stamp = f"crawl {', '.join(Path(c).name for c in a.crawl)}; duel {Path(a.arms).name}; {used} summaries"
    emit(a.out, stamp, teams)
    if a.report:
        R = [f'# Proxy tables ({stamp})', '',
             'Team index k is PROXY_TEAM (k = -1: all twelve pooled). Draft: maps with a lineup, games behind them, the',
             'share of games that used the map\'s most common lineup, and the pick order for maps without data.', '',
             'Recall: share of its contact rounds in which the team started a recall; above 0.5 the proxy ends every',
             'turn with a recall and cancels it next turn (PROXY_PERMA_RECALL).', '',
             '| k | Team | Maps | Games | Modal share | Recall | Fallback order |', '|---:|---|---:|---:|---:|---:|---|']
        for k, (label, nm, total, modal, fallback, items, rc) in enumerate(report):
            R.append(f'| {k - 1} | {label} | {nm} | {total} | {modal:.2f} | {rc:.2f} | {" ".join(fallback)} |')
        R += ['', '## Items', '', 'Opening milestones (shard: owned count), then the stack; agree = share of the',
              "hero's appearances whose first milestones match the opening.", '',
              '| k | Team | Hero | Apps | Agree | Opening | Stack |', '|---:|---|---|---:|---:|---|---|']
        for k, (label, nm, total, modal, fallback, items, rc) in enumerate(report):
            for h, b in items.items():
                op = ' > '.join(f'{i.replace("_shard_of_", " ")} {n}' for i, n in b['open'])
                st = f"{b['main'].replace('_shard_of_', ' ')}" + (f" : {b['health'].replace('_shard_of_', ' ')} = {b['per_health']}:1" if b['per_health'] else ' only')
                R.append(f"| {k - 1} | {label} | {h} | {b['apps']} | {b['agree']:.2f} | {op} | {st} |")
        Path(a.report).write_text('\n'.join(R) + '\n', encoding='utf8', newline='\n')
    print('wrote', a.out, '-', stamp)
    for label, nm, total, modal, fallback, items, rc in report:
        print(f'  {label[:26]:26} maps {nm:2} games {total:5} modal {modal:.2f} heroes {len(items)} recall {rc:.2f}')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('action', choices=['empty', 'mapkeys', 'tables'])
    ap.add_argument('--plan', default=str(ROOT / 'research/v59/duel_top1.json'))
    ap.add_argument('--bot', default=str(ROOT / 'bots/proxy'))
    ap.add_argument('--crawl', nargs='+')
    ap.add_argument('--arms')
    ap.add_argument('--keys')
    ap.add_argument('--style', default=str(ROOT / 'research/proxy/style_ladder.json'))
    ap.add_argument('--workers', type=int, default=16)
    ap.add_argument('--out', required=True)
    ap.add_argument('--report')
    a = ap.parse_args()
    dict(empty=cmd_empty, mapkeys=cmd_mapkeys, tables=cmd_tables)[a.action](a)


if __name__ == '__main__':
    main()
